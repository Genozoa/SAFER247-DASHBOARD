-- Historical baseline schema snapshot. For existing databases, use Alembic upgrade head (currently 0008).
-- DO NOT apply this file over a populated database.
BEGIN;

CREATE TABLE alembic_version (
    version_num VARCHAR(32) NOT NULL, 
    CONSTRAINT alembic_version_pkc PRIMARY KEY (version_num)
);

-- Running upgrade  -> 0001_initial_schema

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE operators (
    id UUID DEFAULT gen_random_uuid() NOT NULL, 
    username TEXT NOT NULL, 
    password_hash TEXT NOT NULL, 
    is_active BOOLEAN DEFAULT true NOT NULL, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    CONSTRAINT pk_operators PRIMARY KEY (id), 
    CONSTRAINT uq_operators_username UNIQUE (username)
);

CREATE TABLE barangays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    name TEXT NOT NULL, 
    boundary geometry(MULTIPOLYGON,4326), 
    centroid geography(POINT,4326), 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    CONSTRAINT pk_barangays PRIMARY KEY (id), 
    CONSTRAINT uq_barangays_name UNIQUE (name)
);

CREATE TABLE incident_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    name TEXT NOT NULL, 
    description TEXT, 
    is_active BOOLEAN DEFAULT true NOT NULL, 
    CONSTRAINT pk_incident_types PRIMARY KEY (id), 
    CONSTRAINT uq_incident_types_name UNIQUE (name)
);

CREATE TABLE responders (
    id UUID DEFAULT gen_random_uuid() NOT NULL, 
    call_sign TEXT NOT NULL, 
    display_name TEXT, 
    is_active BOOLEAN DEFAULT true NOT NULL, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    CONSTRAINT pk_responders PRIMARY KEY (id), 
    CONSTRAINT uq_responders_call_sign UNIQUE (call_sign)
);

CREATE TABLE messages (
    id UUID DEFAULT gen_random_uuid() NOT NULL, 
    direction TEXT NOT NULL, 
    sender_responder_id UUID, 
    sender_operator_id UUID, 
    body TEXT, 
    decoded_payload JSONB, 
    location geography(POINT,4326), 
    sent_at TIMESTAMP WITH TIME ZONE, 
    received_at TIMESTAMP WITH TIME ZONE, 
    transmission_status TEXT DEFAULT 'received' NOT NULL, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    CONSTRAINT pk_messages PRIMARY KEY (id), 
    CONSTRAINT ck_messages_direction_values CHECK (direction IN ('incoming', 'outgoing')), 
    CONSTRAINT ck_messages_sender_matches_direction CHECK ((direction = 'incoming' AND sender_responder_id IS NOT NULL AND sender_operator_id IS NULL) OR (direction = 'outgoing' AND sender_operator_id IS NOT NULL AND sender_responder_id IS NULL)), 
    CONSTRAINT ck_messages_transmission_status_values CHECK (transmission_status IN ('received', 'queued', 'preparing', 'sending', 'audio_complete', 'delivered', 'failed', 'delivery_unknown', 'transmitting', 'sent')),
    CONSTRAINT fk_messages_sender_operator_id_operators FOREIGN KEY(sender_operator_id) REFERENCES operators (id), 
    CONSTRAINT fk_messages_sender_responder_id_responders FOREIGN KEY(sender_responder_id) REFERENCES responders (id)
);

CREATE TABLE incident_reports (
    id UUID DEFAULT gen_random_uuid() NOT NULL, 
    report_code TEXT NOT NULL, 
    source_message_id UUID, 
    incident_type_id BIGINT, 
    responder_id UUID, 
    barangay_id BIGINT, 
    location_description TEXT, 
    details TEXT, 
    location geography(POINT,4326), 
    status TEXT DEFAULT 'received' NOT NULL, 
    reported_at TIMESTAMP WITH TIME ZONE NOT NULL, 
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    CONSTRAINT pk_incident_reports PRIMARY KEY (id), 
    CONSTRAINT fk_incident_reports_barangay_id_barangays FOREIGN KEY(barangay_id) REFERENCES barangays (id) ON DELETE SET NULL, 
    CONSTRAINT fk_incident_reports_incident_type_id_incident_types FOREIGN KEY(incident_type_id) REFERENCES incident_types (id) ON DELETE SET NULL, 
    CONSTRAINT fk_incident_reports_responder_id_responders FOREIGN KEY(responder_id) REFERENCES responders (id) ON DELETE SET NULL, 
    CONSTRAINT fk_incident_reports_source_message_id_messages FOREIGN KEY(source_message_id) REFERENCES messages (id) ON DELETE SET NULL, 
    CONSTRAINT uq_incident_reports_report_code UNIQUE (report_code), 
    CONSTRAINT uq_incident_reports_source_message_id UNIQUE (source_message_id)
);

CREATE TABLE message_transmission_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    message_id UUID NOT NULL, 
    attempt_number INTEGER NOT NULL, 
    status TEXT NOT NULL, 
    attempted_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    result_details TEXT, 
    CONSTRAINT pk_message_transmission_attempts PRIMARY KEY (id), 
    CONSTRAINT ck_message_transmission_attempts_attempt_number_positive CHECK (attempt_number > 0), 
    CONSTRAINT ck_message_transmission_attempts_status_values CHECK (status IN ('queued', 'preparing', 'sending', 'audio_complete', 'delivered', 'failed', 'delivery_unknown', 'transmitting', 'sent')),
    CONSTRAINT fk_message_transmission_attempts_message_id_messages FOREIGN KEY(message_id) REFERENCES messages (id) ON DELETE CASCADE, 
    CONSTRAINT uq_transmission_attempt_number UNIQUE (message_id, attempt_number)
);

CREATE TABLE media_attachments (
    id UUID DEFAULT gen_random_uuid() NOT NULL, 
    message_id UUID, 
    incident_report_id UUID, 
    file_name TEXT NOT NULL, 
    storage_path TEXT NOT NULL, 
    mime_type TEXT NOT NULL, 
    received_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    CONSTRAINT pk_media_attachments PRIMARY KEY (id), 
    CONSTRAINT ck_media_attachments_attachment_has_parent CHECK (message_id IS NOT NULL OR incident_report_id IS NOT NULL), 
    CONSTRAINT fk_media_attachments_incident_report_id_incident_reports FOREIGN KEY(incident_report_id) REFERENCES incident_reports (id) ON DELETE CASCADE, 
    CONSTRAINT fk_media_attachments_message_id_messages FOREIGN KEY(message_id) REFERENCES messages (id) ON DELETE CASCADE
);

CREATE TABLE image_enhancements (
    id UUID DEFAULT gen_random_uuid() NOT NULL, 
    attachment_id UUID NOT NULL, 
    operator_id UUID, 
    enhanced_storage_path TEXT NOT NULL, 
    enhancement_parameters JSONB, 
    enhanced_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    CONSTRAINT pk_image_enhancements PRIMARY KEY (id), 
    CONSTRAINT fk_image_enhancements_attachment_id_media_attachments FOREIGN KEY(attachment_id) REFERENCES media_attachments (id) ON DELETE CASCADE, 
    CONSTRAINT fk_image_enhancements_operator_id_operators FOREIGN KEY(operator_id) REFERENCES operators (id) ON DELETE SET NULL
);

CREATE TABLE responder_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    responder_id UUID NOT NULL, 
    received_message_id UUID, 
    location geography(POINT,4326) NOT NULL, 
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL, 
    received_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
    CONSTRAINT pk_responder_locations PRIMARY KEY (id), 
    CONSTRAINT fk_responder_locations_received_message_id_messages FOREIGN KEY(received_message_id) REFERENCES messages (id) ON DELETE SET NULL, 
    CONSTRAINT fk_responder_locations_responder_id_responders FOREIGN KEY(responder_id) REFERENCES responders (id) ON DELETE CASCADE
);

CREATE TABLE operator_auth (
    operator_id UUID NOT NULL,
    password_fingerprint TEXT NOT NULL,
    CONSTRAINT pk_operator_auth PRIMARY KEY (operator_id),
    CONSTRAINT uq_operator_auth_password_fingerprint UNIQUE (password_fingerprint),
    CONSTRAINT fk_operator_auth_operator_id_operators
        FOREIGN KEY(operator_id) REFERENCES operators (id) ON DELETE CASCADE
);

CREATE TABLE auth_sessions (
    id UUID DEFAULT gen_random_uuid() NOT NULL,
    operator_id UUID NOT NULL,
    token_hash TEXT NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    CONSTRAINT pk_auth_sessions PRIMARY KEY (id),
    CONSTRAINT uq_auth_sessions_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_auth_sessions_operator_id_operators
        FOREIGN KEY(operator_id) REFERENCES operators (id) ON DELETE CASCADE
);

CREATE INDEX idx_barangays_boundary ON barangays USING gist (boundary);

CREATE INDEX idx_incident_reports_barangay_reported_at ON incident_reports (barangay_id, reported_at DESC);

CREATE INDEX idx_incident_reports_location ON incident_reports USING gist (location);

CREATE INDEX idx_incident_reports_reported_at ON incident_reports (reported_at DESC);

CREATE INDEX idx_incident_reports_type_reported_at ON incident_reports (incident_type_id, reported_at DESC);

CREATE INDEX idx_messages_direction_status ON messages (direction, transmission_status);

CREATE INDEX idx_messages_location ON messages USING gist (location);

CREATE INDEX idx_messages_received_at ON messages (received_at DESC);

CREATE INDEX idx_messages_sent_at ON messages (sent_at DESC);

CREATE INDEX idx_responder_locations_location ON responder_locations USING gist (location);

CREATE INDEX idx_responder_locations_responder_recorded_at ON responder_locations (responder_id, recorded_at DESC);

CREATE INDEX idx_auth_sessions_operator_id ON auth_sessions (operator_id);

INSERT INTO alembic_version (version_num) VALUES ('0003_single_operator_name') RETURNING alembic_version.version_num;

COMMIT;
